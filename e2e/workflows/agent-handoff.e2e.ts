test('台后自动启动的原生任务在两个真实工作区分别写读产物，不复用其他工作区环境', async ({ app, screen, browser, dsh }) => {
  const second = join(dsh.root, 'second-workspace')
  mkdirSync(second)
  await dsh.stop(); await dsh.addBundle(fixture); await dsh.start(); await dsh.authenticate(browser)
  await app.open('/')
  await addWorkspace(screen, dsh.workspace)
  for (const [workspace, path, name] of [[dsh.workspaceName, dsh.workspace, 'first-environment'], ['second-workspace', second, 'second-environment']]) {
    if (workspace === 'second-workspace') {
      await screen.getByRole('button', '添加工作区', { exact: true }).tap()
      const picker = screen.getByRole('dialog', '选择工作区目录')
      await picker.getByRole('button', '编辑路径', { exact: true }).tap()
      await picker.getByRole('textbox', '编辑路径').fill(path!)
      await picker.getByRole('textbox', '编辑路径').press('Enter')
      await picker.getByRole('button', '打开', { exact: true }).tap()
      await expect(screen.getByRole('treeitem', '新会话', { exact: true })).toHaveAttribute('aria-selected', 'true')
      await screen.getByRole('button', '工作流', { exact: true }).tap()
    }
    await createInstance(screen, workspace!, 'agent-environment', name!)
    await inspectNode(screen, 'input')
    await screen.getByRole('button', '填写 input', { exact: true }).tap()
  const input = screen.getByRole('dialog', '填写 input', { exact: true })
    await input.getByRole('textbox', '目标工作目录', { exact: true }).fill(realpathSync(path!))
    await input.getByRole('button', '提交表单', { exact: true }).tap()
    await inspectNode(screen, 'task')
    const task = screen.getByRole('complementary', '详情 task')
    await expect(task.getByRole('status')).toHaveText('结果已保存，点击“完成”后交付下游。')
    expect(JSON.parse((await browser.locator('section[aria-label="待确认结果"] pre').textContent())!)).toEqual({ result: 'CONTEXT_MARKER_731', directory: realpathSync(path!) })
    await screen.getByRole('button', '完成 task', { exact: true }).tap()
    await expect(detailField(browser, 'task', '状态')).toHaveText('已完成')
  }
})
