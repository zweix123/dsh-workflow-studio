import { expect } from 'e2e'
import { test } from '../dsh.js'
import { addWorkspace, createInstance, inspectNode } from '../ui.js'
import { fileURLToPath } from 'node:url'

test('rc.1 隐藏后台父会话、fork 继承已结束上下文并 structured_output，原生子记录跨重启可读', async ({ app, screen, browser, dsh }) => {
  await dsh.stop()
  await dsh.addBundle(fileURLToPath(new URL('../fixtures/agent-host', import.meta.url)))
  await dsh.start()
  await dsh.authenticate(browser)
  await app.open('/')
  await addWorkspace(screen, dsh.workspace)
  await createInstance(screen, dsh.workspaceName, 'agent-host-probe', 'host-proof')
  await inspectNode(screen, 'probe')
  await screen.getByRole('button', '验证宿主', { exact: true }).tap()
  const result = screen.getByRole('complementary', '详情 probe').getByLabel('宿主验证结果')
  await expect(result).toContainText('CONTEXT_MARKER_731')
  const proof = JSON.parse((await result.textContent())!)
  expect(proof.status).toBe('waiting')
  expect(proof.compacted).toBe(true)
  expect(proof.idleCompactionExcluded).toBe(true)
  expect(proof.result).toEqual({ result: 'CONTEXT_MARKER_731' })
  await expect(browser.locator(`[data-row-key="session:${proof.parentId}"]`)).toHaveCount(0)
  await screen.getByRole('button', '打开子记录', { exact: true }).tap()
  await expect(screen.getByRole('navigation', '会话层级')).toBeVisible()
  await expect(browser.locator('[contenteditable="true"][role="textbox"]')).not.toBeVisible()
  await expect(browser.locator('body')).toContainText('CONTEXT_MARKER_731')
  await dsh.restart(browser)
  await app.open('/')
  await expect(screen.getByRole('navigation', '会话层级')).toBeVisible()
  await expect(browser.locator('body')).toContainText('CONTEXT_MARKER_731')
  await expect(browser.locator(`[data-row-key="session:${proof.parentId}"]`)).toHaveCount(0)
  await browser.locator('button[aria-label="新建会话"]').nth(0).tap()
  await expect(screen.getByRole('treeitem', '新会话', { exact: true })).toHaveAttribute('aria-selected', 'true')
  expect(await browser.locator('[role="treeitem"][aria-selected="true"]').getAttribute('data-row-key')).not.toBe(`session:${proof.parentId}`)
  await screen.getByRole('button', '工作流', { exact: true }).tap()
  await createInstance(screen, dsh.workspaceName, 'regression-session', 'ordinary-chat')
  await inspectNode(screen, 'task')
  await screen.getByRole('complementary', '详情 task').getByRole('button', '执行', { exact: true }).tap()
  await screen.getByRole('button', '打开对话', { exact: true }).tap()
  await expect(browser.locator(`[data-row-key="session:${proof.parentId}"]`)).toHaveCount(0)
  expect(await browser.locator('[role="treeitem"][aria-selected="true"]').getAttribute('data-row-key')).not.toBe(`session:${proof.parentId}`)
})
