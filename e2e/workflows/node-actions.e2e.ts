test('第三方节点固定第 1 和 3 位，图标文字统一且卡片与动作独立键盘操作', async ({ app, screen, browser, dsh }) => {
  await dsh.stop()
  await dsh.addBundle(fileURLToPath(new URL('../../packages/dsh-workflow-studio/tests/fixtures/browser-node', import.meta.url)))
  await dsh.start()
  await dsh.authenticate(browser)
  await app.open('/')
  await addWorkspace(screen, dsh.workspace)
  await createInstance(screen, dsh.workspaceName, 'browser-probe', 'positions')
  const cardSelector = '.dsh-workflow-studio-panel:not([hidden]) .dsh-workflow-node[data-definition-id="probe"]'
  const card = browser.locator(cardSelector)
  const action = (selector: string) => browser.locator(`${cardSelector} ${selector}`)
  await expect(action('[data-action-position]')).toHaveCount(3)
  await expect(action('[data-action-position="2"] button')).toHaveCount(0)
  await expect(action('[data-action-position="1"] button svg')).toHaveCount(1)
  await expect(action('[data-action-position="3"] button')).toHaveText('Fail synchronously')
  await screen.getByRole('button', 'Fail synchronously probe', { exact: true }).press('Enter')
  await expect(screen.getByRole('alert')).toContainText('probe synchronous error')
  await expect(screen.getByRole('complementary')).toHaveCount(0)
  await screen.getByRole('button', '详情 probe', { exact: true }).press('Enter')
  const details = screen.getByRole('complementary', '详情 probe', { exact: true })
  await expect(details.getByRole('button')).toHaveCount(1)
  await screen.getByRole('button', '关闭详情', { exact: true }).tap()
  await screen.getByRole('button', 'Run probe probe', { exact: true }).press('Space')
  await expect(card).toContainText('已完成')
  await expect(action('[data-action-position="1"] button')).toHaveCount(0)
  await expect(screen.getByRole('complementary')).toHaveCount(0)
})

test('Form 自管原生浮窗保留草稿与校验反馈，成功自动关闭，详情只读且中英文主题窄屏可用', async ({ app, screen, browser, dsh }) => {
  await app.open('/')
  await addWorkspace(screen, dsh.workspace)
  await createInstance(screen, dsh.workspaceName, 'form-structured-e2e', 'modal-lifecycle')
  await inspectNode(screen, 'collect')
  await expect(browser.locator('aside :is(input, textarea, select)')).toHaveCount(0)
  await screen.getByRole('button', '关闭详情', { exact: true }).tap()
  await screen.getByRole('button', '填写 collect', { exact: true }).press('Enter')
  const form = screen.getByRole('dialog', '填写 collect', { exact: true })
  await form.getByLabel('备注 / Note', { exact: true }).fill('page draft')
  await form.getByRole('button', '添加 flags', { exact: true }).tap()
  await form.getByRole('button', '提交表单', { exact: true }).tap()
  await expect(form.getByRole('alert')).toContainText('form.flags[0]')
  await form.getByLabel('备注 / Note', { exact: true }).press('Escape')
  await expect(form).not.toBeVisible()
  await expect.poll(() => browser.evaluate(() => document.activeElement?.getAttribute('aria-label') ?? null)).toBe('填写 collect')
  await screen.getByRole('button', '填写 collect', { exact: true }).tap()
  await expect(form.getByLabel('备注 / Note', { exact: true })).toHaveValue('page draft')
  await form.getByRole('button', '关闭表单', { exact: true }).tap()
  await screen.getByRole('button', '设置', { exact: true }).tap()
  await screen.getByRole('button', '深色', { exact: true }).tap()
  await screen.getByRole('button', '关闭', { exact: true }).tap()
  await screen.getByRole('button', '填写 collect', { exact: true }).tap()
  await expect(form.getByLabel('备注 / Note', { exact: true })).toHaveValue('page draft')
  await form.getByRole('button', '关闭表单', { exact: true }).tap()
  await screen.getByRole('button', '设置', { exact: true }).tap()
  await screen.getByRole('button', '浅色', { exact: true }).tap()
  await screen.getByRole('button', '中文', { exact: true }).tap()
  await screen.getByRole('menuitem', 'English', { exact: true }).tap()
  await screen.getByRole('button', 'Close', { exact: true }).tap()
  await browser.setViewport({ width: 390, height: 844 })
  await screen.getByRole('button', 'Fill in collect', { exact: true }).press('Space')
  const english = screen.getByRole('dialog', 'Fill in collect', { exact: true })
  await expect(english.getByLabel('备注 / Note', { exact: true })).toHaveValue('page draft')
  await expect.poll(() => browser.evaluate(() => {
    const dialog = document.querySelector('[role="dialog"][aria-label="Fill in collect"]')!
    return dialog.scrollWidth <= dialog.clientWidth
  })).toBe(true)
  await english.getByRole('group', 'flags 1', { exact: true }).getByRole('switch').press('Space')
  await english.getByRole('group', 'flags 1', { exact: true }).getByRole('switch').press('Space')
  await english.getByRole('button', 'Submit form', { exact: true }).tap()
  await expect(english).not.toBeVisible()
  await expect(screen.getByRole('button', 'Fill in collect', { exact: true })).toHaveCount(0)
  await screen.getByRole('button', 'Details collect', { exact: true }).press('Enter')
  await expect(screen.getByRole('complementary', 'Details collect', { exact: true })).toContainText('page draft')
  await expect(browser.locator('aside :is(input, textarea, select)')).toHaveCount(0)
})

test('Form 草稿按实例隔离，同页面切换保留，宿主重启后丢弃未提交草稿', async ({ app, screen, browser, dsh }) => {
  await app.open('/')
  await addWorkspace(screen, dsh.workspace)
  await createInstance(screen, dsh.workspaceName, 'form-structured-e2e', 'draft-first')
  await screen.getByRole('button', '填写 collect', { exact: true }).tap()
  const form = screen.getByRole('dialog', '填写 collect', { exact: true })
  await form.getByLabel('备注 / Note', { exact: true }).fill('first instance only')
  await form.getByRole('button', '关闭表单', { exact: true }).tap()
  await createInstance(screen, dsh.workspaceName, 'form-structured-e2e', 'draft-second')
  await screen.getByRole('button', '填写 collect', { exact: true }).tap()
  await expect(form.getByLabel('备注 / Note', { exact: true })).toHaveValue('')
  await form.getByRole('button', '关闭表单', { exact: true }).tap()
  await screen.getByRole('tab', 'draft-first', { exact: true }).tap()
  await screen.getByRole('button', '填写 collect', { exact: true }).tap()
  await expect(form.getByLabel('备注 / Note', { exact: true })).toHaveValue('first instance only')
  await form.getByRole('button', '关闭表单', { exact: true }).tap()
  await dsh.restart(browser)
  await app.open('/')
  await expect(browser.locator('[role="treeitem"][aria-selected="true"]')).toBeVisible()
  await screen.getByRole('button', '工作流', { exact: true }).tap()
  await screen.getByRole('button', /^draft-first/).tap()
  await screen.getByRole('button', '填写 collect', { exact: true }).tap()
  await expect(form.getByLabel('备注 / Note', { exact: true })).toHaveValue('')
})

test('Form 已接受结果交付失败保留原生浮窗与只读结果，关闭后第 1 位只重交且重启不开放编辑', async ({ app, screen, browser, dsh }) => {
  await app.open('/')
  await addWorkspace(screen, dsh.workspace)
  await createInstance(screen, dsh.workspaceName, 'form-structured-retry', 'form-accepted-error')
  await screen.getByRole('button', '填写 answer', { exact: true }).tap()
  const form = screen.getByRole('dialog', '填写 answer', { exact: true })
  await form.getByRole('button', '提交表单', { exact: true }).tap()
  await expect(form.getByRole('alert')).toContainText('MISSING_OUTPUT_FIELD')
  await expect(browser.locator('[role="dialog"][aria-label="填写 answer"] :is(input, textarea, select):not(:disabled)')).toHaveCount(0)
  await expect(form.getByRole('button', '提交表单', { exact: true })).toHaveCount(0)
  await expect(form.getByRole('button', '重试提交结果', { exact: true })).toBeEnabled()
  await form.getByRole('button', '关闭表单', { exact: true }).tap()
  await expect(screen.getByRole('button', '填写 answer', { exact: true })).toHaveCount(0)
  await expect(screen.getByRole('button', '重试提交结果 answer', { exact: true })).toBeEnabled()
  await inspectNode(screen, 'answer')
  const accepted = JSON.parse((await detailField(browser, 'answer', '输出').textContent())!)
  expect(accepted.enabled).toBe(false)
  await expect(browser.locator('aside :is(input, textarea, select)')).toHaveCount(0)
  await screen.getByRole('button', '重试提交结果 answer', { exact: true }).tap()
  await expect(screen.getByRole('dialog', '填写 answer', { exact: true })).toHaveCount(0)
  expect(JSON.parse((await detailField(browser, 'answer', '输出').textContent())!)).toEqual(accepted)
  await dsh.restart(browser)
  await app.open('/')
  await expect(browser.locator('[role="treeitem"][aria-selected="true"]')).toBeVisible()
  await screen.getByRole('button', '工作流', { exact: true }).tap()
  await screen.getByRole('button', /^form-accepted-error/).tap()
  await inspectNode(screen, 'answer')
  expect(JSON.parse((await detailField(browser, 'answer', '输出').textContent())!)).toEqual(accepted)
  await expect(screen.getByRole('button', '填写 answer', { exact: true })).toHaveCount(0)
  await expect(screen.getByRole('button', '重试提交结果 answer', { exact: true })).toBeEnabled()
})
