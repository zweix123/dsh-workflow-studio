import { expect } from 'e2e'
import { fileURLToPath } from 'node:url'
import { readFile } from 'node:fs/promises'
import { join } from 'node:path'
import { test, type DshHost } from '../dsh.js'
import { addWorkspace, createInstance, detailField, inspectNode, openWorkflows } from '../ui.js'

async function installDevelopmentTemplates(dsh: DshHost, browser: Parameters<DshHost['authenticate']>[0]) {
  await dsh.stop()
  await dsh.addBundle(fileURLToPath(new URL('../../packages/dsh-workflow-dev-templates', import.meta.url)))
  await dsh.start()
  await dsh.authenticate(browser)
}

test('开发模板按需附加，默认入口无开发模板，四份资源及 Agent 嵌套定义重启后可用', async ({ app, screen, browser, dsh }) => {
  await app.open('/')
  await addWorkspace(screen, dsh.workspace)
  await screen.getByRole('tab', '模板管理', { exact: true }).tap()
  await expect(screen.getByRole('button', /^打开模板 开发 ·/)).toHaveCount(0)
  await expect(screen.getByRole('button', '打开模板 OpenSpec 变更工作流', { exact: true })).toBeEnabled()

  await installDevelopmentTemplates(dsh, browser)
  await app.open('/')
  await openWorkflows(screen, browser)
  await screen.getByRole('tab', '模板管理', { exact: true }).tap()
  const templates = ['表单节点功能', 'Bash 节点功能', 'Bash 失败与重试', 'Agent 节点功能']
  for (const name of templates) await expect(screen.getByRole('button', `打开模板 开发 · ${name}`, { exact: true })).toBeEnabled()
  await expect(browser.locator('.dsh-workflow-template-item > code').filter({ hasText: '@dsh-workflow/dev-templates/templates/' })).toHaveCount(4)
  await screen.getByRole('button', '打开模板 开发 · Agent 节点功能', { exact: true }).tap()
  const definition = (field: string) => browser.locator(`.dsh-workflow-studio-panel:not([hidden]) section[aria-label="定义详情"] dt:text-is("${field}") + dd pre`)
  await inspectNode(screen, '台前讨论')
  await expect(definition('node_kind')).toHaveText('agent')
  await expect(definition('mode')).toHaveText('foreground')
  await inspectNode(screen, '台后整理')
  await expect(definition('mode')).toHaveText('background')
  await expect(definition('is_auto_start')).toHaveText('true')
  await inspectNode(screen, '台后整理组')
  await expect(definition('type')).toHaveText('dag')
  await createInstance(screen, dsh.workspaceName, 'dev-agent.zh', 'dev-agent-inspection')
  await inspectNode(screen, '台后整理组')
  await expect(detailField(browser, '台后整理组', '状态')).toHaveText('等待')
  await expect(browser.locator('.dsh-workflow-studio-panel:not([hidden]) .dsh-workflow-plugin-details')).toHaveCount(0)
  await dsh.restart(browser)
  await app.open('/')
  await openWorkflows(screen, browser)
  await expect(screen.getByRole('button', /^dev-agent-inspection/)).toHaveCount(1)
  await screen.getByRole('tab', '模板管理', { exact: true }).tap()
  for (const name of templates) await expect(screen.getByRole('button', `打开模板 开发 · ${name}`, { exact: true })).toBeEnabled()
})

test('开发表单展示枚举和多选、对象数组及真实预填，提交结果跨重启只读', async ({ app, screen, browser, dsh }) => {
  await installDevelopmentTemplates(dsh, browser)
  await app.open('/')
  await addWorkspace(screen, dsh.workspace)
  await createInstance(screen, dsh.workspaceName, 'dev-form.zh', 'dev-form-run')
  await screen.getByRole('button', '填写 填写资料', { exact: true }).tap()
  const form = screen.getByRole('dialog', '填写 填写资料', { exact: true })
  await expect(form.getByLabel('说明', { exact: true })).toHaveValue('为新同事安排入门任务。')
  await expect(form.getByRole('option', '普通', { exact: true })).toHaveCount(1)
  await form.getByLabel('说明', { exact: true }).fill('真实预填：中文、"引号"和换行\n第二行。')
  await form.getByLabel('负责人', { exact: true }).fill('开发验收')
  await form.getByRole('button', '添加 任务', { exact: true }).tap()
  await form.getByRole('button', '删除 任务 1', { exact: true }).tap()
  await form.getByRole('checkbox', '文档', { exact: true }).tap()
  await form.getByRole('checkbox', '代码', { exact: true }).tap()
  await form.getByRole('button', '提交表单', { exact: true }).tap()
  await expect(form).not.toBeVisible()
  await inspectNode(screen, '填写资料')
  const output = {
    note: '真实预填：中文、"引号"和换行\n第二行。', priority: 0, approved: false,
    settings: { owner: '开发验收', enabled: false }, tasks: [{ title: '新任务', hours: 0 }], tags: ['code'],
  }
  expect(JSON.parse((await detailField(browser, '填写资料', '输出').textContent())!)).toEqual(output)
  await screen.getByRole('button', '填写 核对预填', { exact: true }).tap()
  const review = screen.getByRole('dialog', '填写 核对预填', { exact: true })
  await expect(review.getByLabel('说明', { exact: true })).toHaveValue(output.note)
  await expect(review.getByLabel('优先级', { exact: true })).toHaveValue('0')
  await expect(review.getByRole('switch', '已确认', { exact: true })).not.toBeChecked()
  await expect(review.getByRole('checkbox', '代码', { exact: true })).toBeChecked()
  await review.getByRole('button', '删除 任务 1', { exact: true }).tap()
  await review.getByRole('button', '提交表单', { exact: true }).tap()
  await expect(review).not.toBeVisible()
  await inspectNode(screen, '核对预填')
  expect(JSON.parse((await detailField(browser, '核对预填', '输出').textContent())!)).toEqual({ ...output, tasks: [] })
  await dsh.restart(browser)
  await app.open('/')
  await openWorkflows(screen, browser)
  await screen.getByRole('button', /^dev-form-run/).tap()
  await inspectNode(screen, '核对预填')
  await expect(detailField(browser, '核对预填', '状态')).toHaveText('已完成')
  expect(JSON.parse((await detailField(browser, '核对预填', '输出').textContent())!)).toEqual({ ...output, tasks: [] })
  await expect(screen.getByRole('button', '填写 核对预填', { exact: true })).toHaveCount(0)
})

test('开发 Bash 的真实手动和自动命令保留特殊输入，无输出仅日志，重启后不重跑', async ({ app, screen, browser, dsh }) => {
  await installDevelopmentTemplates(dsh, browser)
  await app.open('/')
  await addWorkspace(screen, dsh.workspace)
  await createInstance(screen, dsh.workspaceName, 'dev-bash.zh', 'dev-bash-run')
  await screen.getByRole('button', '填写 填写命令输入', { exact: true }).tap()
  const form = screen.getByRole('dialog', '填写 填写命令输入', { exact: true })
  const request = '中文、"引号"、单引号\'与换行\n$HOME、$(printf injected)、`printf injected` 保持原文。'
  await form.getByRole('textbox', '命令输入', { exact: true }).fill(request)
  await form.getByRole('button', '提交表单', { exact: true }).tap()
  await expect(form).not.toBeVisible()
  await inspectNode(screen, '手动命令')
  await screen.getByRole('button', '执行 手动命令', { exact: true }).tap()
  await expect(detailField(browser, '手动命令', '状态')).toHaveText('已完成')
  expect(JSON.parse((await detailField(browser, '手动命令', '输出').textContent())!)).toEqual({ prepared_request: request })
  await inspectNode(screen, '自动命令')
  await expect(detailField(browser, '自动命令', '状态')).toHaveText('已完成')
  expect(JSON.parse((await detailField(browser, '自动命令', '输出').textContent())!)).toEqual({ prepared_request: request })
  await screen.getByRole('button', '填写 核对命令结果', { exact: true }).tap()
  const review = screen.getByRole('dialog', '填写 核对命令结果', { exact: true })
  await expect(review.getByRole('textbox', '命令结果', { exact: true })).toHaveValue(request)
  await review.getByRole('button', '提交表单', { exact: true }).tap()
  await expect(review).not.toBeVisible()
  await inspectNode(screen, '无输出命令')
  await screen.getByRole('button', '执行 无输出命令', { exact: true }).tap()
  await expect(detailField(browser, '无输出命令', '状态')).toHaveText('已完成')
  expect(JSON.parse((await detailField(browser, '无输出命令', '输出').textContent())!)).toEqual({})
  await expect(browser.locator('aside[aria-label="详情 无输出命令"]')).toContainText('这段 stdout 是日志，不作为业务输出')
  await dsh.restart(browser)
  await app.open('/')
  await openWorkflows(screen, browser)
  await screen.getByRole('button', /^dev-bash-run/).tap()
  await inspectNode(screen, '自动命令')
  await expect(detailField(browser, '自动命令', '状态')).toHaveText('已完成')
  expect(JSON.parse((await detailField(browser, '自动命令', '输出').textContent())!)).toEqual({ prepared_request: request })
  await expect(screen.getByRole('button', '执行 自动命令', { exact: true })).toHaveCount(0)
})

test('开发 Bash 重试专题两次失败不推进，第三次成功交付并恢复计数', async ({ app, screen, browser, dsh }) => {
  await installDevelopmentTemplates(dsh, browser)
  await app.open('/')
  await addWorkspace(screen, dsh.workspace)
  await createInstance(screen, dsh.workspaceName, 'dev-bash-retry.zh', 'dev-bash-retry-run')
  for (const expected of ['Command exited with code 7', 'INVALID_FIELD_TYPE']) {
    await inspectNode(screen, '失败后重试')
    await screen.getByRole('button', `${expected === 'Command exited with code 7' ? '执行' : '重新执行'} 失败后重试`, { exact: true }).tap()
    await expect(detailField(browser, '失败后重试', '状态')).toHaveText('执行异常')
    await expect(screen.getByRole('complementary', '详情 失败后重试', { exact: true })).toContainText(expected)
    await inspectNode(screen, '核对重试结果')
    await expect(detailField(browser, '核对重试结果', '状态')).toHaveText('等待')
  }
  await inspectNode(screen, '失败后重试')
  await screen.getByRole('button', '重新执行 失败后重试', { exact: true }).tap()
  await expect(detailField(browser, '失败后重试', '状态')).toHaveText('已完成')
  await expect.poll(() => readFile(join(dsh.workspace, '.dsh-dev-bash-retry.json'), 'utf8')).toBe('3')
  await screen.getByRole('button', '填写 核对重试结果', { exact: true }).tap()
  const form = screen.getByRole('dialog', '填写 核对重试结果', { exact: true })
  await expect(form.getByRole('textbox', '重试结果', { exact: true })).toHaveValue('第三次执行已交付有效结果。')
  await form.getByRole('button', '提交表单', { exact: true }).tap()
  await expect(form).not.toBeVisible()
  await dsh.restart(browser)
  await app.open('/')
  await openWorkflows(screen, browser)
  await screen.getByRole('button', /^dev-bash-retry-run/).tap()
  await inspectNode(screen, '失败后重试')
  await expect(detailField(browser, '失败后重试', '状态')).toHaveText('已完成')
  expect(await readFile(join(dsh.workspace, '.dsh-dev-bash-retry.json'), 'utf8')).toBe('3')
})
