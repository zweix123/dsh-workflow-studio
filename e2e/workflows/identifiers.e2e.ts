import { expect } from 'e2e'
import { mkdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { stringify } from 'yaml'
import { test } from '../dsh.js'
import { addWorkspace, createInstance, detailField, inspectNode, openWorkflows } from '../ui.js'

const panel = '.dsh-workflow-studio-panel:not([hidden])'
const longName = '一个用于验证窄屏和长名称显示的中文处理任务'

test('中文名称和 ID 回退保持同名实体的独立操作、布局连线及宿主重启恢复', async ({ app, screen, browser, dsh }) => {
  await browser.setViewport({ width: 1440, height: 900 })
  await app.open('/')
  await addWorkspace(screen, dsh.workspace)
  await screen.getByRole('tab', '模板管理', { exact: true }).tap()
  await screen.getByRole('button', '打开模板 regression-identifiers', { exact: true }).tap()
  const card = (id: string) => browser.locator(`${panel} [data-graph-node][data-definition-id="${id}"]`)
  const layout = () => browser.evaluate(panel => [...document.querySelectorAll(`${panel} [data-graph-node]`)].map(card => ({
    id: card.getAttribute('data-definition-id'), transform: (card.closest('.react-flow__node') as HTMLElement).style.transform,
  })), panel)
  await expect(card('first')).toContainText('同名任务')
  await expect(card('second')).toContainText('同名任务')
  await expect(card('fallback')).toContainText('fallback')
  await expect(card('nested').first()).toContainText('中文递归流程')
  await expect(card('step')).toContainText(longName)
  await expect(browser.locator(`${panel} .react-flow__edge-path`)).toHaveCount(4)
  await screen.getByRole('button', /^中文依赖:/).tap()
  await expect(screen.getByRole('dialog', '完整表达式')).toContainText('中文依赖')
  await screen.getByRole('button', '关闭表达式', { exact: true }).tap()
  const preview = await layout()
  expect(new Set(preview.map(row => row.transform)).size).toBeGreaterThan(2)

  await createInstance(screen, dsh.workspaceName, 'regression-identifiers', 'named-run')
  await expect(card('first')).toContainText('同名任务')
  await expect(card('second')).toContainText('同名任务')
  await expect(browser.locator(`${panel} .react-flow__edge-path`)).toHaveCount(3)
  await card('first').getByRole('button', '执行 同名任务', { exact: true }).tap()
  await expect(card('first')).toHaveAttribute('data-status', 'completed')
  await expect(card('second')).toHaveAttribute('data-status', 'ready')
  await card('second').tap()
  await expect(detailField(browser, '同名任务', '节点实例')).toContainText('second · ')
  const secondId = await detailField(browser, '同名任务', '节点实例').textContent()
  await screen.getByRole('button', '关闭详情', { exact: true }).tap()
  const before = await layout()
  await dsh.restart(browser)
  await app.open('/')
  await openWorkflows(screen, browser)
  await screen.getByRole('button', /^named-run/).tap()
  await expect(card('first')).toHaveAttribute('data-status', 'completed')
  await card('second').tap()
  await expect(detailField(browser, '同名任务', '节点实例')).toHaveText(secondId!)
  await screen.getByRole('button', '关闭详情', { exact: true }).tap()
  expect(await layout()).toEqual(before)
  await card('second').getByRole('button', '执行 同名任务', { exact: true }).tap()
  await expect(card('second')).toHaveAttribute('data-status', 'completed')
  await inspectNode(screen, 'fallback')
  await screen.getByRole('button', '执行 fallback', { exact: true }).tap()
  await expect(detailField(browser, 'fallback', '状态')).toHaveText('已完成')
  await inspectNode(screen, longName)
  await screen.getByRole('button', '关闭详情', { exact: true }).tap()
  await screen.getByRole('button', '查看全图', { exact: true }).tap()
  await screen.getByRole('button', `执行 ${longName}`, { exact: true }).tap()
  await expect(browser.locator(`${panel} [data-definition-id="step"][data-status="completed"]`)).toHaveCount(1)
  await expect(browser.locator(`${panel} .dsh-workflow-dag-group[data-definition-id="nested"]`)).toHaveCount(2)
  await expect(card('step')).toHaveCount(2)
  await screen.getByRole('button', '查看全图', { exact: true }).tap()
  await browser.locator(`${panel} [data-definition-id="step"][data-status="ready"]`).getByRole('button', `执行 ${longName}`, { exact: true }).tap()
  await expect(browser.locator(`${panel} [data-definition-id="step"][data-status="completed"]`)).toHaveCount(2)

  await screen.getByRole('button', '设置', { exact: true }).tap()
  await screen.getByRole('button', '深色', { exact: true }).tap()
  await screen.getByRole('button', '关闭', { exact: true }).tap()
  await expect(card('first')).toContainText('同名任务')
  await screen.getByRole('button', '设置', { exact: true }).tap()
  await screen.getByRole('button', '浅色', { exact: true }).tap()
  await screen.getByRole('button', '中文', { exact: true }).tap()
  await screen.getByRole('menuitem', 'English', { exact: true }).tap()
  await screen.getByRole('button', 'Close', { exact: true }).tap()
  await browser.setViewport({ width: 390, height: 844 })
  await screen.getByRole('button', 'Fit all', { exact: true }).tap()
  await expect(card('first')).toContainText('同名任务')
  await card('step').first().tap()
  await expect(screen.getByRole('heading', longName, { exact: true })).toBeVisible()
  expect(await browser.evaluate(panel => {
    const inspector = document.querySelector(`${panel} .dsh-workflow-inspector`)!
    return inspector.scrollWidth <= inspector.clientWidth
  }, panel)).toBe(true)
})

test('非法逐项 key 提交回滚且真实宿主重启不留下部分任务', async ({ app, screen, browser, dsh }) => {
  await app.open('/')
  await addWorkspace(screen, dsh.workspace)
  await createInstance(screen, dsh.workspaceName, 'regression-identifier-keys', 'invalid-keys')
  await inspectNode(screen, '产生非法 key')
  const original = await detailField(browser, '产生非法 key', '节点实例').textContent()
  await screen.getByRole('button', '执行 产生非法 key', { exact: true }).tap()
  await expect(browser.locator(`${panel} .dsh-workflow-inspector [role="alert"]`)).toContainText('INVALID_FOR_KEY')
  await expect(detailField(browser, '产生非法 key', '状态')).toHaveText('就绪')
  await inspectNode(screen, '处理项')
  await expect(detailField(browser, '处理项', '状态')).toHaveText('等待')
  await expect(detailField(browser, '处理项', '节点实例')).toHaveCount(0)
  await expect(screen.getByRole('button', /^详情 处理项 /)).toHaveCount(0)
  await dsh.restart(browser)
  await app.open('/')
  await openWorkflows(screen, browser)
  await screen.getByRole('button', /^invalid-keys/).tap()
  await inspectNode(screen, '产生非法 key')
  await expect(detailField(browser, '产生非法 key', '节点实例')).toHaveText(original!)
  await expect(detailField(browser, '产生非法 key', '状态')).toHaveText('就绪')
  await expect(browser.locator(`${panel} .dsh-workflow-inspector [role="alert"]`)).toContainText('INVALID_FOR_KEY')
  await inspectNode(screen, '处理项')
  await expect(detailField(browser, '处理项', '状态')).toHaveText('等待')
  await expect(detailField(browser, '处理项', '节点实例')).toHaveCount(0)
})

test('源模板改名后重启保留实例的根、嵌套、节点及边名称快照', async ({ app, screen, browser, dsh }) => {
  const directory = join(dsh.root, 'snapshot-template')
  await mkdir(directory)
  await writeFile(join(directory, 'package.json'), JSON.stringify({ name: '@dsh-workflow/identifier-snapshot', version: '0.1.0', private: true, type: 'module', exports: { './workflow.yaml': './workflow.yaml' }, dsh: { bundle: { patch: './cordis.patch.yml' } } }))
  await writeFile(join(directory, 'cordis.patch.yml'), stringify([{ insert: [{ id: 'identifier-snapshot', name: 'dsh-workflow-template', config: { directory: '@dsh-workflow/identifier-snapshot' } }] }]))
  const definition = (prefix: string) => ({ id: 'identifier-snapshot', name: `${prefix}模板`, type: 'dag', dag: [{
    id: 'nested', name: `${prefix}嵌套`, type: 'dag', dag: [
      { id: 'task', name: `${prefix}节点`, type: 'node', node_kind: 'bash', command: '' },
      { id: 'fallback', type: 'node', node_kind: 'bash', command: '' },
      { id: 'link', name: `${prefix}依赖`, type: 'edge', from: 'task', to: 'fallback', if: 'true' },
    ],
  }] })
  await writeFile(join(directory, 'workflow.yaml'), stringify(definition('原')))
  await dsh.stop()
  await dsh.addBundle(directory)
  await dsh.start()
  await dsh.authenticate(browser)
  await app.open('/')
  await addWorkspace(screen, dsh.workspace)
  await createInstance(screen, dsh.workspaceName, 'identifier-snapshot', 'snapshot-names')
  await inspectNode(screen, '原节点')
  const identity = await detailField(browser, '原节点', '节点实例').textContent()
  await writeFile(join(directory, 'workflow.yaml'), stringify(definition('新')))
  await dsh.restart(browser)
  await app.open('/')
  await openWorkflows(screen, browser)
  await screen.getByRole('tab', '模板管理', { exact: true }).tap()
  await screen.getByRole('button', '打开模板 新模板', { exact: true }).tap()
  await expect(screen.getByRole('button', '详情 新嵌套', { exact: true })).toBeVisible()
  await expect(screen.getByRole('button', '详情 新节点', { exact: true })).toBeVisible()
  await expect(screen.getByRole('button', /^新依赖:/)).toBeVisible()
  await screen.getByRole('tab', '实例管理', { exact: true }).tap()
  await screen.getByRole('button', /^snapshot-names/).tap()
  await expect(browser.locator(`${panel} .dsh-workflow-detail-header p`)).toHaveText('原模板')
  await expect(screen.getByRole('button', '详情 原嵌套', { exact: true })).toBeVisible()
  await expect(screen.getByRole('button', /^原依赖:/)).toBeVisible()
  await inspectNode(screen, '原节点')
  await expect(detailField(browser, '原节点', '节点实例')).toHaveText(identity!)
  await screen.getByRole('button', '执行 原节点', { exact: true }).tap()
  await expect(detailField(browser, '原节点', '状态')).toHaveText('已完成')
  await inspectNode(screen, 'fallback')
  await expect(detailField(browser, 'fallback', '状态')).toHaveText('就绪')
})
