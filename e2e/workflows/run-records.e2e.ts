import { expect } from 'e2e'
import { readFile } from 'node:fs/promises'
import { join } from 'node:path'
import { test } from '../dsh.js'
import { addWorkspace, createInstance, detailField, inspectNode, openWorkflows } from '../ui.js'

test('Bash 历次失败与成功保留输入、命令和日志，最新展开，重启仍只读', async ({ app, screen, browser, dsh }) => {
  await app.open('/')
  await addWorkspace(screen, dsh.workspace)
  await createInstance(screen, dsh.workspaceName, 'regression-bash', 'records')
  await inspectNode(screen, 'retry')
  await screen.getByRole('button', '执行 retry', { exact: true }).tap()
  await expect(detailField(browser, 'retry', '状态')).toHaveText('执行异常')
  const historySelector = 'aside[aria-label="详情 retry"] section[aria-label="运行记录"]'
  const history = browser.locator(historySelector)
  await expect(history).toContainText('first attempt failed')
  await screen.getByRole('button', '重新执行 retry', { exact: true }).tap()
  await expect(history).toContainText('INVALID_FIELD_TYPE')
  await screen.getByRole('button', '重新执行 retry', { exact: true }).tap()
  await expect(detailField(browser, 'retry', '状态')).toHaveText('已完成')
  await expect(browser.locator(`${historySelector} details`)).toHaveCount(3)
  await expect(browser.locator(`${historySelector} details[open]`)).toHaveCount(1)
  await expect(browser.locator(`${historySelector} details:first-child`)).toContainText('成功')
  await expect(browser.locator(`${historySelector} details:first-child`)).toContainText('hello from upstream')
  await browser.locator(`${historySelector} details:nth-child(3) summary`).press('Enter')
  await expect(browser.locator(`${historySelector} details:nth-child(3)`)).toContainText('first attempt failed')
  await expect(browser.locator(`${historySelector} details:nth-child(3)`)).toContainText('attempts.txt')
  expect(await readFile(join(dsh.workspace, 'attempts.txt'), 'utf8')).toBe('attempt\nattempt\nattempt\n')
  await dsh.restart(browser)
  await app.open('/')
  await openWorkflows(screen, browser)
  await screen.getByRole('button', /^records/).tap()
  await inspectNode(screen, 'retry')
  await expect(browser.locator(`${historySelector} details`)).toHaveCount(3)
  await expect(browser.locator(`${historySelector} button`)).toHaveCount(0)
  expect(await readFile(join(dsh.workspace, 'attempts.txt'), 'utf8')).toBe('attempt\nattempt\nattempt\n')
})

test('台后 Agent 金刚位仅业务交互，最新与旧执行记录均从详情抽屉打开', async ({ app, screen, browser, dsh }) => {
  const { fileURLToPath } = await import('node:url')
  await dsh.stop(); await dsh.addBundle(fileURLToPath(new URL('../fixtures/agent-host', import.meta.url))); await dsh.start(); await dsh.authenticate(browser)
  await app.open('/')
  await addWorkspace(screen, dsh.workspace)
  await createInstance(screen, dsh.workspaceName, 'agent-failures', 'agent-records')
  await inspectNode(screen, 'retry')
  const history = 'aside[aria-label="详情 retry"] section[aria-label="运行记录"]'
  await screen.getByRole('button', '执行 retry', { exact: true }).tap()
  await expect(detailField(browser, 'retry', '状态')).toHaveText('执行异常')
  await expect(browser.locator(history)).toContainText('FAIL_ONCE_TASK')
  await screen.getByRole('button', '重试 retry', { exact: true }).tap()
  await expect(browser.locator(`${history} details:first-child`)).toContainText('待确认')
  await expect(browser.locator(`${history} details`)).toHaveCount(2)
  await expect(screen.getByRole('button', '执行记录 retry', { exact: true })).toHaveCount(0)
  await expect(browser.locator('[data-graph-node][data-definition-id="retry"] [data-action-position="1"] button')).toHaveCount(0)
  await browser.locator(`${history} details:first-child button`).press('Enter')
  await expect(browser.locator('body')).toContainText('一次性子智能体记录')
  await expect(screen.getByRole('dialog', '历次尝试', { exact: true })).toHaveCount(0)
  await screen.getByRole('button', '返回实例', { exact: true }).tap()
  await expect(screen.getByRole('heading', 'agent-records', { exact: true })).toBeVisible()
  await expect(detailField(browser, 'retry', '状态')).toHaveText('就绪')
  await browser.locator(`${history} details:nth-child(2) summary`).press('Enter')
  await browser.locator(`${history} details:nth-child(2) button`).press('Enter')
  await expect(browser.locator('body')).toContainText('Fixture task failed')
  await screen.getByRole('button', '返回实例', { exact: true }).tap()
  await expect(screen.getByRole('heading', 'agent-records', { exact: true })).toBeVisible()
  await expect(browser.locator(`${history} details`)).toHaveCount(2)
  await expect(screen.getByRole('button', '完成 retry', { exact: true })).toBeEnabled()
})

