test('Bash 宿主截断日志在当次记录中明确标识，合法空输出与日志分开', async ({ app, screen, browser, dsh }) => {
  await app.open('/')
  await addWorkspace(screen, dsh.workspace)
  await createInstance(screen, dsh.workspaceName, 'regression-run-records', 'truncated-records')
  await inspectNode(screen, 'overflow')
  await screen.getByRole('button', '执行 overflow', { exact: true }).tap()
  await expect(detailField(browser, 'overflow', '状态')).toHaveText('已完成')
  const history = browser.locator('aside section[aria-label="运行记录"]')
  await expect(history).toContainText('日志已截断')
  await expect(history).toContainText('stdout-evidence')
  await expect(history).toContainText('stderr-evidence')
  expect(JSON.parse((await detailField(browser, 'overflow', '输出').textContent())!)).toEqual({})
  await expect(browser.locator('aside section[aria-label="运行记录"] details')).toHaveCount(1)
})
