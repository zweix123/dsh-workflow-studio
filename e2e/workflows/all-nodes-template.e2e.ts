import { expect } from 'e2e'
import { fileURLToPath } from 'node:url'
import { test } from '../dsh.js'
import { addWorkspace, createInstance, detailField, inspectNode } from '../ui.js'

test('独立全节点示例可加载创建，表单与 Bash 原样交付并展示两种 Agent 及嵌套 DAG', async ({ app, screen, browser, dsh }) => {
  await dsh.stop()
  await dsh.addBundle(fileURLToPath(new URL('../../examples/all-nodes', import.meta.url)))
  await dsh.start()
  await dsh.authenticate(browser)
  await app.open('/')
  await addWorkspace(screen, dsh.workspace)
  await screen.getByRole('tab', '模板管理', { exact: true }).tap()
  await screen.getByRole('button', '打开模板 全节点类型示例', { exact: true }).tap()
  await inspectNode(screen, '台前讨论')
  const definition = (field: string) => browser.locator(`.dsh-workflow-studio-panel:not([hidden]) section[aria-label="定义详情"] dt:text-is("${field}") + dd pre`)
  await expect(definition('node_kind')).toHaveText('agent')
  await expect(definition('mode')).toHaveText('foreground')
  await inspectNode(screen, '台后整理')
  await expect(definition('node_kind')).toHaveText('agent')
  await expect(definition('mode')).toHaveText('background')
  await inspectNode(screen, '台后整理组')
  await expect(definition('type')).toHaveText('dag')

  await createInstance(screen, dsh.workspaceName, 'all-nodes-example.zh', 'all-nodes-example')
  await inspectNode(screen, '填写需求')
  await screen.getByRole('button', '填写 填写需求', { exact: true }).tap()
  const form = screen.getByRole('dialog', '填写 填写需求', { exact: true })
  await expect(form.getByRole('textbox', '示例需求', { exact: true })).toHaveValue('为新同事设计一个简单的项目入门流程。')
  const request = '中文、"引号"、单引号\'与换行\n$HOME 与 $(printf injected) 保持原文。'
  await form.getByRole('textbox', '示例需求', { exact: true }).fill(request)
  await form.getByRole('button', '提交表单', { exact: true }).tap()
  await expect(detailField(browser, '填写需求', '状态')).toHaveText('已完成')
  await inspectNode(screen, '命令处理')
  await screen.getByRole('button', '执行 命令处理', { exact: true }).tap()
  await expect(detailField(browser, '命令处理', '状态')).toHaveText('已完成')
  expect(JSON.parse((await detailField(browser, '命令处理', '输出').textContent())!)).toEqual({ prepared_request: request })
  await inspectNode(screen, '台前讨论')
  await expect(detailField(browser, '台前讨论', '状态')).toHaveText('就绪')
  expect(JSON.parse((await detailField(browser, '台前讨论', '输入').textContent())!)).toEqual({ prepared_request: request })
  await expect(screen.getByRole('button', '执行 台前讨论', { exact: true })).toBeEnabled()
  await inspectNode(screen, '台后整理组')
  await expect(detailField(browser, '台后整理组', '状态')).toHaveText('等待')
  await expect(browser.locator('.dsh-workflow-studio-panel:not([hidden]) .dsh-workflow-plugin-details')).toHaveCount(0)
})
