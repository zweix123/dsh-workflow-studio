import { expect } from 'e2e'
import { test } from '../dsh.js'
import { addWorkspace, createInstance, detailField, inspectNode, openWorkflows } from '../ui.js'

test('枚举显示名称与真实类型、多选增删、空数组、下游预填及宿主重启恢复', async ({ app, screen, browser, dsh }) => {
  await app.open('/')
  await addWorkspace(screen, dsh.workspace)
  await createInstance(screen, dsh.workspaceName, 'regression-form-enums', 'enum-handoff')
  await screen.getByRole('button', '填写 collect', { exact: true }).tap()
  const form = screen.getByRole('dialog', '填写 collect', { exact: true })
  await expect(form.getByLabel('优先级 / Priority')).toHaveValue('1')
  await expect(form.getByRole('option', '中优先级 / Medium', { exact: true })).toHaveText('中优先级 / Medium')
  await expect(form.getByRole('option', '零 / Zero', { exact: true })).toHaveText('零 / Zero')
  await expect(form.getByRole('option', '否 / No', { exact: true })).toHaveText('否 / No')
  await expect(form.getByRole('option', '草稿 / Draft', { exact: true })).toHaveText('草稿 / Draft')
  await expect(form.getByRole('option', 'ready', { exact: true })).toHaveText('ready')
  await form.getByLabel('优先级 / Priority').selectOption({ label: '高优先级 / High' })
  await form.getByLabel('级别 / Level', { exact: true }).selectOption({ label: '一 / One' })
  await form.getByLabel('批准 / Approved').selectOption({ label: '是 / Yes' })
  await form.getByLabel('状态 / State').selectOption({ label: 'ready' })
  await expect(form.getByRole('checkbox', '前端 / Frontend')).toBeChecked()
  await form.getByRole('checkbox', '前端 / Frontend').press('Space')
  await form.getByRole('checkbox', '测试 / Test').press('Space')
  await form.getByRole('checkbox', '后端 / Backend').press('Space')
  await form.getByRole('checkbox', '测试 / Test').press('Space')
  await form.getByRole('checkbox', '测试 / Test').press('Space')
  await expect(form.getByRole('button', '添加 标签 / Tags', { exact: true })).toHaveCount(0)
  await form.getByRole('listbox', '多选级别 / Levels').press('Home')
  await form.getByRole('listbox', '多选级别 / Levels').press('Shift+ArrowDown')
  await expect(form.getByRole('checkbox', '布尔否 / Boolean no')).toBeChecked()
  await form.getByRole('checkbox', '布尔是 / Boolean yes').press('Space')
  await expect(form.getByRole('checkbox', 'x', { exact: true })).not.toBeChecked()
  const repeat = form.getByRole('group', '普通枚举列表 / Repeat', { exact: true })
  await expect(repeat.getByRole('combobox')).toHaveCount(2)
  await expect(repeat.getByRole('button', '添加 普通枚举列表 / Repeat', { exact: true })).toBeEnabled()
  await form.getByRole('button', '关闭表单', { exact: true }).tap()
  await screen.getByRole('button', '填写 collect', { exact: true }).tap()
  await expect(form.getByRole('checkbox', '后端 / Backend')).toBeChecked()
  await expect(form.getByRole('checkbox', '前端 / Frontend')).not.toBeChecked()
  await form.getByRole('button', '提交表单', { exact: true }).tap()
  await expect(form).not.toBeVisible()
  const expected = { priority: 'high', level: 1, approved: true, settings: { state: 'ready' }, tags: ['backend', 'test'], levels: [0, 1], flags: [false, true], empty: [], repeat: ['a', 'a'] }
  await inspectNode(screen, 'collect')
  expect(JSON.parse((await detailField(browser, 'collect', '输出').textContent())!)).toEqual(expected)
  await screen.getByRole('button', '关闭详情', { exact: true }).tap()
  await screen.getByRole('button', '填写 review', { exact: true }).tap()
  const review = screen.getByRole('dialog', '填写 review', { exact: true })
  await expect(review.getByLabel('优先级 / Priority')).toHaveValue('0')
  await expect(review.getByRole('checkbox', '后端 / Backend')).toBeChecked()
  await expect(review.getByRole('checkbox', '前端 / Frontend')).not.toBeChecked()
  await expect(review.getByRole('checkbox', '布尔否 / Boolean no')).toBeChecked()
  await expect(review.getByRole('checkbox', 'x', { exact: true })).not.toBeChecked()
  await expect.poll(() => browser.evaluate(() => Array.from(document.querySelector<HTMLSelectElement>('[role="dialog"] select[multiple]')!.selectedOptions, option => option.value))).toEqual(['0', '1'])
  await review.getByRole('button', '提交表单', { exact: true }).tap()
  await expect(review).not.toBeVisible()
  await expect(screen.getByRole('button', '填写 review', { exact: true })).toHaveCount(0)
  await dsh.restart(browser)
  await app.open('/')
  await openWorkflows(screen, browser)
  await screen.getByRole('button', /^enum-handoff/).tap()
  await inspectNode(screen, 'review')
  expect(JSON.parse((await detailField(browser, 'review', '输出').textContent())!)).toEqual(expected)
  await expect(browser.locator('aside :is(input, textarea, select)')).toHaveCount(0)
})

test('多选在深浅主题、英文和窄屏下可键盘操作，取消全部选择提交空数组', async ({ app, screen, browser, dsh }) => {
  await app.open('/')
  await addWorkspace(screen, dsh.workspace)
  await createInstance(screen, dsh.workspaceName, 'regression-form-enums', 'enum-empty')
  for (const theme of ['深色', '浅色']) {
    await screen.getByRole('button', '设置', { exact: true }).tap()
    await screen.getByRole('button', theme, { exact: true }).tap()
    await screen.getByRole('button', '关闭', { exact: true }).tap()
    await screen.getByRole('button', '填写 collect', { exact: true }).press('Enter')
    const form = screen.getByRole('dialog', '填写 collect', { exact: true })
    await expect(form.getByRole('checkbox', '前端 / Frontend')).toBeChecked()
    await form.getByRole('button', '关闭表单', { exact: true }).tap()
  }
  await screen.getByRole('button', '设置', { exact: true }).tap()
  await screen.getByRole('button', '中文', { exact: true }).tap()
  await screen.getByRole('menuitem', 'English', { exact: true }).tap()
  await screen.getByRole('button', 'Close', { exact: true }).tap()
  await browser.setViewport({ width: 390, height: 844 })
  await screen.getByRole('button', 'Fill in collect', { exact: true }).press('Space')
  const form = screen.getByRole('dialog', 'Fill in collect', { exact: true })
  await expect.poll(() => browser.evaluate(() => {
    const dialog = document.querySelector('[role="dialog"][aria-label="Fill in collect"]')!
    return dialog.scrollWidth <= dialog.clientWidth
  })).toBe(true)
  await form.getByRole('checkbox', '前端 / Frontend').press('Space')
  await form.getByRole('checkbox', '布尔否 / Boolean no').press('Space')
  await form.getByRole('listbox', '多选级别 / Levels').getByRole('option', '零级 / Zero level', { exact: true }).tap({ modifiers: [process.platform === 'darwin' ? 'Meta' : 'Control'] })
  await form.getByRole('button', 'Submit form', { exact: true }).tap()
  await expect(form).not.toBeVisible()
  await screen.getByRole('button', 'Details collect', { exact: true }).tap()
  const output = browser.locator('aside[aria-label="Details collect"] section[aria-label="Running information"] dt:text-is("Output") + dd pre')
  const value = JSON.parse((await output.textContent())!)
  expect(value.tags).toEqual([])
  expect(value.levels).toEqual([])
  expect(value.flags).toEqual([])
  expect(value.level).toBe(0)
  expect(value.approved).toBe(false)
})

test('重复上游预填不会静默去重，表单拒绝提交并保留草稿，取消重选后交付唯一值', async ({ app, screen, browser, dsh }) => {
  await app.open('/')
  await addWorkspace(screen, dsh.workspace)
  await createInstance(screen, dsh.workspaceName, 'regression-form-enum-duplicates', 'enum-duplicates')
  await screen.getByRole('button', '填写 source', { exact: true }).tap()
  await screen.getByRole('dialog', '填写 source', { exact: true }).getByRole('button', '提交表单', { exact: true }).tap()
  await screen.getByRole('button', '查看全图', { exact: true }).tap()
  await screen.getByRole('button', '填写 review', { exact: true }).tap()
  const form = screen.getByRole('dialog', '填写 review', { exact: true })
  await expect(form.getByRole('checkbox', '选项 A')).toBeChecked()
  await form.getByRole('button', '提交表单', { exact: true }).tap()
  await expect(form.getByRole('alert')).toContainText('form.tags[1]')
  await expect(form.getByRole('alert')).toContainText('uniqueItems')
  await form.getByRole('button', '关闭表单', { exact: true }).tap()
  await screen.getByRole('button', '填写 review', { exact: true }).tap()
  await expect(form.getByRole('checkbox', '选项 A')).toBeChecked()
  await form.getByRole('button', '提交表单', { exact: true }).tap()
  await expect(form.getByRole('alert')).toContainText('uniqueItems')
  await form.getByRole('checkbox', '选项 A').press('Space')
  await form.getByRole('checkbox', '选项 A').press('Space')
  await form.getByRole('button', '提交表单', { exact: true }).tap()
  await expect(form).not.toBeVisible()
  await inspectNode(screen, 'review')
  expect(JSON.parse((await detailField(browser, 'review', '输出').textContent())!)).toEqual({ tags: ['a'] })
})
